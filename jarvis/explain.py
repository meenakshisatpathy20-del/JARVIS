"""Incident report: always a template report; a Gemini narrative on top when available.

The LLM never chooses the root cause, never sees raw logs or user IDs, and the dashboard
never waits for it (temperature 0, short timeout, template fallback).
"""
import json
import os
import threading

import httpx

from .common import hms, scrub

PROMPT = (
    "You are an incident reporter. Explain the diagnosis below to an on-call engineer in under "
    "120 words: what broke, why we believe it (cite the evidence), who is affected, and the first "
    "fix to try. Do not change the root cause. If confidence is \"Not sure\", say so and name both "
    "candidates. Amounts are estimates on synthetic traffic.\n\nDIAGNOSIS JSON:\n"
)


def summary(inc: dict) -> dict:
    """Structured summary sent to the LLM: no raw log lines, no user IDs, no per-user amounts."""
    return {
        "title": inc["title"], "severity": f"SEV{inc['severity']}", "confidence": inc["confidence"],
        "root_cause": inc["top"],
        "candidates": [{"service": c["service"], "score": c["score"], "evidence": [scrub(e) for e in c["evidence"]]}
                       for c in inc["candidates"]],
        "healthy_dependencies": inc.get("healthy_dependencies", []),
        "impact": {k: v for k, v in inc["impact"].items()},
        "timeline": [{"time": t["time"], "event": scrub(t["text"])} for t in inc["timeline"][:20]],
        "first_fix": inc["recommendations"][0]["title"] if inc["recommendations"] else None,
    }


def template_report(inc: dict) -> str:
    im = inc["impact"]
    top = inc["candidates"][0] if inc["candidates"] else None
    lines = [f"**{inc['title']}** (SEV{inc['severity']}, confidence: {inc['confidence']})", ""]
    if inc["confidence"] == "Not sure" and len(inc["candidates"]) > 1:
        lines.append(f"J.A.R.V.I.S. is **not sure** between {inc['candidates'][0]['service']} and "
                     f"{inc['candidates'][1]['service']}. {inc.get('not_sure_check') or ''}")
    elif top:
        lines.append(f"Likely root cause: **{top['service']}**. Why we believe it:")
        lines += [f"- {e}" for e in top["evidence"]]
    if inc.get("healthy_dependencies"):
        lines.append(f"- Healthy dependencies: {', '.join(inc['healthy_dependencies'])}.")
    lines += ["", f"Impact ({im['label']}): {im['affected_users']} users affected; "
              f"{im['failed_logins_per_min']} failed logins/min; {im['failed_payments_per_min']} failed payments/min; "
              f"{im['slow_payments_per_min']} slow payments/min; estimated ₹{im['est_inr_at_risk_per_min']:,.0f} at risk per minute.",
              ""]
    if inc["recommendations"]:
        r = inc["recommendations"][0]
        lines.append(f"First fix to try: **{r['title']}**: {r['steps'][0]}")
    return "\n".join(lines)


def markdown_report(inc: dict) -> str:
    im = inc["impact"]
    md = [f"# Incident {inc['id']}: {inc['title']}", "",
          f"- Severity: SEV{inc['severity']} (peak SEV{inc['peak_severity']})",
          f"- Status: {inc['status']}", f"- Opened: {inc['opened_at']}",
          f"- Likely root cause: {inc['top']} (confidence: {inc['confidence']})",
          f"- Source: {inc['origin']}", "", "## Summary", "", inc.get("report") or inc["template_report"], "",
          "## Evidence (top 3 candidates)", ""]
    for c in inc["candidates"]:
        t = c["terms"]
        md.append(f"### {c['service']}: score {c['score']} (A={t['A']}, O={t['O']}, L={t['L']}, C={t['C']}, X={t['X']})")
        md += [f"- {e}" for e in c["evidence"]] or ["- (no supporting evidence)"]
        md.append("")
    md += ["## Impact (estimated, synthetic traffic)", ""]
    md += [f"- {k.replace('_', ' ')}: {v}" for k, v in im.items() if k != "label"]
    md += ["", "## Timeline", ""] + [f"- {t['time']}  {t['text']}" for t in inc["timeline"]]
    md += ["", "## Recommendations", ""]
    for r in inc["recommendations"]:
        md.append(f"### {r['title']}")
        md += [f"1. {s}" for s in r["steps"]]
        md.append(f"\n_Addresses:_ {r['addresses']}\n")
    md += ["## What simple rules would have said", ""]
    md += [f"- {k.replace('_', ' ')}: {v}" for k, v in inc["baselines"].items()]
    md.append("\n_Generated by J.A.R.V.I.S. The root cause is chosen by a deterministic evidence score; "
              "the narrative is written by an LLM only when available._")
    return "\n".join(md)


class Explainer:
    def __init__(self, cfg: dict):
        self.model = os.getenv("GEMINI_MODEL", cfg["llm"]["model"])
        self.timeout = float(cfg["llm"]["timeout_s"])
        self.key = os.getenv("GEMINI_API_KEY", "").strip()
        self.cache = {}
        self.pending = set()
        self.lock = threading.Lock()
        self.status = "no API key: template reports" if not self.key else "ready"

    def get(self, inc: dict):
        """Return (text, source). Kicks off a background Gemini call when the diagnosis changes."""
        if not self.key:
            return None, "template"
        s = summary(inc)
        sig = json.dumps([s["root_cause"], s["confidence"], s["severity"], s["candidates"][0]["evidence"] if s["candidates"] else []])
        key = (inc["id"], sig)
        with self.lock:
            if key in self.cache:
                return self.cache[key], "gemini"
            if key not in self.pending:
                self.pending.add(key)
                threading.Thread(target=self._call, args=(key, s), daemon=True).start()
        # while waiting, keep showing the last good narrative for this incident, if any
        with self.lock:
            prev = [v for (iid, _), v in self.cache.items() if iid == inc["id"]]
        return (prev[-1], "gemini (updating)") if prev else (None, "template")

    def _call(self, key, s):
        try:
            url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent"
            body = {"contents": [{"parts": [{"text": PROMPT + json.dumps(s, indent=1)}]}],
                    "generationConfig": {"temperature": 0, "maxOutputTokens": 400,
                                         "thinkingConfig": {"thinkingBudget": 0}}}
            r = httpx.post(url, json=body, headers={"x-goog-api-key": self.key}, timeout=self.timeout)
            r.raise_for_status()
            text = r.json()["candidates"][0]["content"]["parts"][0]["text"].strip()
            with self.lock:
                self.cache[key] = scrub(text)
            self.status = "ok"
        except Exception as e:  # timeout, rate limit, bad key: template stays
            self.status = f"fallback to template ({type(e).__name__})"
        finally:
            with self.lock:
                self.pending.discard(key)
